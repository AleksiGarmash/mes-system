package com.mes.qr;

import java.util.UUID;

/**
 * Полезная нагрузка QR-кода №2 ("QR задания"), печатаемого на каждом
 * экземпляре чек-листа при выдаче в цех. Кодирует, какое именно
 * производственное задание и рецептуру представляет собой этот бланк —
 * чтобы не полагаться на OCR для самого критичного поля документа.
 * <p>
 * Не путать с QR-кодом шаблона макета (когда появятся шаблоны бланков) —
 * тот кодирует раскладку полей и одинаков для всего тиража одного вида бланка,
 * этот — уникален для каждого отпечатанного листа.
 */
public record OrderQrPayload(
        UUID orderId,
        String orderNo,
        String recipeCode,
        Integer recipeVersion
) {
}
