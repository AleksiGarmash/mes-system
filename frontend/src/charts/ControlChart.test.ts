import { spreadLabels } from './ControlChart'

describe('подписи линий не налезают друг на друга', () => {
  it('сдвигает близкие подписи вниз на минимальный зазор, сохраняя порядок', () => {
    expect(spreadLabels([100, 104, 300], 15)).toEqual([100, 115, 300])
  })
  it('работает при любом порядке входа', () => {
    expect(spreadLabels([104, 100], 15)).toEqual([115, 100])
  })
  it('далёкие подписи не трогает', () => {
    expect(spreadLabels([10, 50, 90], 15)).toEqual([10, 50, 90])
  })
})
